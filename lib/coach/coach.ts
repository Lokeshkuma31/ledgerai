export interface MemoryStats {
  totalEntries: number;
}

export interface ReviewStats {
  totalTransactions: number;
  reviewedCount: number;
  pendingCount: number;
}

/** Structured merchant knowledge, not a raw name/alias — the Coach reasons
 * about "Amazon, E-Commerce, ₹12,000 across 5 visits" rather than parsing
 * free-form transaction notes itself. */
export interface MerchantCoachSummary {
  canonicalName: string;
  industry: string;
  category: string;
  tags: string[];
  isRecurringFriendly: boolean;
  transactionCount: number;
  totalSpend: number;
  averageTransactionAmount: number;
}

export interface CoachInput {
  insights: Insights;
  timeline: TimelineGroup[];
  /** Last 10 transactions, newest first. */
  recentTransactions: Transaction[];
  /** Merchant Knowledge Graph profiles — the Coach consumes these instead
   * of raw merchant names or aliases. */
  merchantSummaries: MerchantCoachSummary[];
  memoryStats: MemoryStats;
  reviewStats: ReviewStats;
  /** Already-computed by the Budget Engine — the LLM must not recalculate these. */
  budgetStatuses: BudgetStatus[];
  /** Already-detected by the Events Engine — the LLM must not discover these itself. */
  events: FinancialEvent[];
  /** Already-generated by the Decision Engine — the LLM must not invent new ones. */
  recommendations: Recommendation[];
  /** Already-detected by the Recurring Transaction Intelligence Engine —
   * the LLM must not try to spot recurring behavior itself. */
  recurringSummaries: RecurringCoachSummary[];
  /** Already-computed by the Cash Flow Forecast Engine — the LLM explains
   * this, it never calculates a projection itself. */
  forecastSummary: ForecastCoachSummary | null;
  /** Already-generated by the Financial Insight & Explanation Engine —
   * each one's `reason` and `supportingEvidence` are the authoritative
   * explanation for its object. The LLM narrates these, it never derives
   * its own reasoning from the raw analytics below. */
  explanations: ExplanationCoachSummary[];
  /** Already-generated and already-prioritized by the Financial Intelligence
   * Feed Engine — the top items from the user's feed. The LLM summarizes
   * these; it never generates a feed item itself. */
  feedSummaries: FeedCoachSummary[];
  /** Already-decided by the Automation & Notification Policy Engine —
   * pending/suppressed/briefing-bound notification candidates. The LLM
   * summarizes these; it must never decide notification policy itself. */
  policySummary: PolicyCoachSummary;
  /** Already-executed by the Financial Workflow Engine — recent workflow
   * runs it coordinated across the other engines. The LLM narrates what
   * happened; it never triggers or decides a workflow itself. */
  workflowSummaries: WorkflowCoachSummary[];
  /** Already-computed by the Savings Goals Engine — progress, pace, and
   * on-track status for each goal. The LLM narrates these; it must never
   * calculate goal progress or savings pace itself. */
  goalSummaries: GoalCoachSummary[];
  /** Already-computed by transaction-source plugins (e.g. the Android SMS
   * & Notification Source Plugin) via registerCoachImportSummaryContributor
   * — how many messages each contributed, how many became transactions,
   * duplicates, and failures. The LLM only narrates these as background
   * context; it never re-parses or re-imports anything itself. Empty when
   * no such plugin is installed/enabled. */
  importSummaries: CoachImportSummaryContribution[];
  /** Already-computed by the Bank Connector Framework via
   * registerCoachAccountSummaryContributor — connected account count,
   * combined balance, and which accounts haven't synced recently. The
   * LLM only narrates this; it must never talk to a connector, compute a
   * balance, or decide what counts as "stale" itself. Empty when no bank
   * accounts are connected. */
  accountSummaries: BankCoachAccountSummary[];
  /** Already-executed by the Unified Synchronization Engine via
   * registerCoachSyncSummaryContributor — one summary per completed sync
   * job across every connected provider (Email, Bank, SMS, Document,
   * future plugins). The LLM only narrates these; it must never trigger,
   * decide, or re-run a synchronization itself. Empty when nothing has
   * synced yet. */
  syncSummaries: SyncCoachSummary[];
}

export interface CoachOutput {
  summary: string;
  goodHabits: string[];
  watchOutFor: string[];
  suggestions: string[];
}

function effectiveCategory(transaction: Transaction): string {
  return transaction.userCategory ?? transaction.aiCategory ?? "Other";
}

function buildAnalyticsPayload(input: CoachInput) {
  return {
    totalSpent: input.insights.totalSpent,
    transactionCount: input.insights.totalTransactions,
    categoryBreakdown: input.insights.categoryBreakdown.map((entry) => ({
      category: entry.category,
      total: entry.total,
      percentage: Math.round(entry.percentage * 10) / 10,
    })),
    timelineSummary: input.timeline.map((group) => ({
      period: group.label,
      totalAmount: group.totalAmount,
      transactionCount: group.transactionCount,
    })),
    largestExpense: input.insights.largestExpense,
    mostUsedCategory: input.insights.topCategory,
    mostUsedPaymentMethod: input.insights.topPaymentMethod,
    averageExpense: input.insights.averageExpense,
    recentTransactions: input.recentTransactions.slice(0, 10).map((t) => ({
      amount: t.amount,
      category: effectiveCategory(t),
      paymentMethod: t.paymentMethod,
      date: t.date,
    })),
    merchants: input.merchantSummaries.map((m) => ({
      name: m.canonicalName,
      industry: m.industry,
      category: m.category,
      tags: m.tags,
      isRecurringFriendly: m.isRecurringFriendly,
      transactionCount: m.transactionCount,
      totalSpend: m.totalSpend,
      averageTransactionAmount: Math.round(m.averageTransactionAmount),
    })),
    memoryLayer: {
      rememberedMappingCount: input.memoryStats.totalEntries,
    },
    review: {
      totalTransactions: input.reviewStats.totalTransactions,
      reviewedCount: input.reviewStats.reviewedCount,
      pendingCount: input.reviewStats.pendingCount,
    },
    budgets: input.budgetStatuses.map((b) => ({
      category: b.category,
      monthlyLimit: b.monthlyLimit,
      currentSpend: b.currentSpend,
      remainingAmount: b.remainingAmount,
      percentageUsed: Math.round(b.percentageUsed * 10) / 10,
      transactionCount: b.transactionCount,
      daysRemainingThisMonth: b.daysRemainingThisMonth,
      status: b.status,
    })),
    events: input.events.map((e) => ({
      type: e.type,
      title: e.title,
      description: e.description,
      date: e.date,
      severity: e.severity,
    })),
    recommendations: input.recommendations.map((r) => ({
      title: r.title,
      description: r.description,
      category: r.category,
      priority: r.priority,
      reason: r.reason,
      action: r.action,
    })),
    recurring: input.recurringSummaries.map((r) => ({
      title: r.title,
      frequency: r.frequency,
      averageAmount: Math.round(r.averageAmount),
      nextExpectedOccurrence: r.nextExpectedOccurrence,
      status: r.status,
      isSubscription: r.isSubscription,
      isIncome: r.isIncome,
    })),
    forecast: input.forecastSummary && {
      projectedEndOfMonthBalance: Math.round(input.forecastSummary.projectedEndOfMonthBalance),
      expectedIncome: Math.round(input.forecastSummary.expectedIncome),
      expectedExpenses: Math.round(input.forecastSummary.expectedExpenses),
      expectedSavings: Math.round(input.forecastSummary.expectedSavings),
      dailySafeSpend: Math.round(input.forecastSummary.dailySafeSpend),
      confidence: Math.round(input.forecastSummary.confidence * 100) / 100,
      daysRemaining: input.forecastSummary.daysRemaining,
      categoryRisks: input.forecastSummary.categoryRisks.map((c) => ({
        category: c.category,
        riskLevel: c.riskLevel,
        projectedPercentageUsed:
          c.projectedPercentageUsed === null ? null : Math.round(c.projectedPercentageUsed),
      })),
    },
    explanations: input.explanations.map((e) => ({
      objectType: e.objectType,
      title: e.title,
      reason: e.reason,
      supportingEvidence: e.supportingEvidence,
      confidence: Math.round(e.confidence * 100) / 100,
    })),
    feed: input.feedSummaries.map((f) => ({
      type: f.type,
      title: f.title,
      summary: f.summary,
      priority: f.priority,
      severity: f.severity,
      sourceEngine: f.sourceEngine,
    })),
    notifications: {
      pending: input.policySummary.pendingCandidates,
      suppressedCount: input.policySummary.suppressedCount,
      dailyBriefing: input.policySummary.dailyBriefingCandidates,
    },
    workflows: input.workflowSummaries.map((w) => ({
      name: w.name,
      trigger: w.trigger,
      status: w.status,
      stepCount: w.stepCount,
    })),
    goals: input.goalSummaries.map((g) => ({
      name: g.name,
      targetAmount: g.targetAmount,
      currentAmount: g.currentAmount,
      percentComplete: g.percentComplete,
      daysRemaining: g.daysRemaining,
      status: g.status,
      monthlySavingsNeeded: g.monthlySavingsNeeded,
    })),
    importSummaries: input.importSummaries.map((s) => ({
      plugin: s.pluginName,
      totalMessages: s.totalMessages,
      importedCount: s.importedCount,
      duplicateCount: s.duplicateCount,
      failedCount: s.failedCount,
      lastImportAt: s.lastImportAt,
    })),
    accounts: input.accountSummaries.map((a) => ({
      connectedAccountCount: a.connectedAccountCount,
      combinedBalance: Math.round(a.combinedBalance),
      currency: a.currency,
      staleAccounts: a.staleAccounts.map((s) => ({
        accountName: s.accountName,
        institution: s.institution,
        daysSinceSync: s.daysSinceSync,
      })),
    })),
    sync: input.syncSummaries.map((s) => ({
      provider: s.providerName,
      category: s.category,
      status: s.status,
      itemsImported: s.itemsImported,
      itemsSkipped: s.itemsSkipped,
      duplicates: s.duplicates,
      completedAt: s.completedAt,
    })),
  };
}

